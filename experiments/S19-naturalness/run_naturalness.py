"""
S19 — how much of "sounds processed" is the codec, and how much is the model?

`S14b` failed its own control in a useful way: the listener called an UNTOUCHED
render "processed". So the baseline synthesis is audibly synthetic, and every
naturalness assumption downstream of that is open. But "it sounds processed" is
not actionable — it does not say whether to change the codec, the LM, or
neither.

THE DESIGN DECOMPOSES IT. Three versions of the same utterance:

    A  real       the original IndicVoices-R recording
    B  roundtrip  that same recording encoded and decoded by MioCodec, with
                  ITS OWN global embedding -- the codec's contribution alone,
                  no LM involved
    C  synthesis  the same text generated by Indic-Mio and decoded with the
                  same speaker's embedding -- codec AND model

    A vs B   what the CODEC costs
    B vs C   what the MODEL costs on top
    A vs C   the total

That is the whole point: "processed" splits into two causes with different
fixes. If B already sounds processed, a better LM will not help and the codec
is the thing to change. If B is clean and C is not, the codec is fine.

WHY THE SAME TEXT AND THE SAME SPEAKER EVERYWHERE. Otherwise the listener can
answer on content or on voice rather than on naturalness. IndicVoices-R ships
transcripts, so C says exactly what A says, in A's own voice.

THE CONTROL is a real-vs-real pair. Two different real recordings, same
question. A listener who can reliably pick a "more real" one out of two real
clips is answering on something else -- room noise, loudness, accent -- and no
other answer in the set can be read.

LEVEL-MATCHED throughout, because loudness is the easiest unintended cue.

    envs/qwen3/Scripts/python.exe experiments/S19-naturalness/run_naturalness.py
"""
import argparse
import io
import json
import os
import sys
import warnings

warnings.filterwarnings("ignore")
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import numpy as np
import torch

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
from alaap.acoustics import measure
from alaap.data import stream_clips

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")
os.makedirs(OUT, exist_ok=True)

ap = argparse.ArgumentParser()
ap.add_argument("--corpus", default="indicvoices_r_hi")
ap.add_argument("--items", type=int, default=3, help="utterances, each giving A/B/C")
ap.add_argument("--codec", default="Aratako/MioCodec-25Hz-44.1kHz-v2")
ap.add_argument("--lm", default="SPRINGLab/Indic-Mio")
ap.add_argument("--seed", type=int, default=19)
# The codec and the LM are loaded in SEPARATE PROCESSES. Together they
# segfaulted on a box with 2.7 GB of 15.7 GB free -- a system-RAM failure
# during model load, nothing to do with the 6 GB GPU, which sat at 614 MiB.
# Phase 1 does A and B (codec only), phase 2 does C (LM), and each caches
# its output so the peak footprint is one model rather than two.
ap.add_argument("--phase", default="all", choices=["codec", "lm", "decode", "pairs", "all"])
args = ap.parse_args()

SR_CORPUS, SR_CODEC = 24000, 44100
SPEECH_OFFSET, CODEBOOK = 151669, 12800

import librosa
import soundfile as sf


def level(w, target_dbfs=-23.0):
    """Match loudness. Amplitude is the easiest cue to answer on by accident."""
    w = np.asarray(w, np.float32)
    r = float(np.sqrt(np.mean(w ** 2)))
    if r < 1e-8:
        return w
    g = 10 ** (target_dbfs / 20.0) / r
    return np.clip(w * g, -1.0, 1.0).astype(np.float32)


print(f"[1/4] collecting {args.items + 2} clips with transcripts from {args.corpus}")
# Keep only what is needed: the wav and the transcript. Holding 60 Clip
# objects alive alongside two models exhausted OpenBLAS's allocator on a 6 GB
# card, and the streamer cannot be told how many to KEEP, only how many to
# scan -- so the filtering has to happen here and the rest dropped immediately.
CLIP_CACHE = os.path.join(OUT, f"clips_{args.corpus}_{args.items + 2}.npz")
if os.path.exists(CLIP_CACHE):
    z = np.load(CLIP_CACHE, allow_pickle=True)
    clips = [{"wav": z[f"w{i}"], "text": str(z["texts"][i]),
              "speaker_id": str(z["spk"][i])} for i in range(int(z["n"]))]
    print(f"      cached: {len(clips)} clips")
else:
    clips = []
    for c in stream_clips(args.corpus, n=args.items * 6, per_speaker=1, dev_only=True,
                          min_dur=3.0, max_dur=8.0, progress_every=10):
        txt = (getattr(c, "text", "") or "").strip()
        if len(txt) < 20:
            continue
        clips.append({"wav": np.asarray(c.wav, np.float32).copy(), "text": txt,
                      "speaker_id": getattr(c, "speaker_id", "?")})
        if len(clips) >= args.items + 2:
            break
    if len(clips) < args.items + 2:
        sys.exit(f"only {len(clips)} usable clips; need {args.items + 2}")
    np.savez_compressed(
        CLIP_CACHE, n=len(clips),
        texts=np.array([c["text"] for c in clips], dtype=object),
        spk=np.array([c["speaker_id"] for c in clips], dtype=object),
        **{f"w{i}": c["wav"] for i, c in enumerate(clips)})
    print(f"      {len(clips)} clips cached")

# The streamer holds decoder buffers that are still resident when the models
# load, and on this box that was enough to fail a tokenizer read with
# MemoryError -- a SYSTEM RAM failure, not a GPU one, so it looked unrelated.
# Dropping the iterator and forcing a collection before the models is the fix;
# caching above means a re-run never streams at all.
import gc
gc.collect()

AB_CACHE = os.path.join(OUT, "ab.npz")
C_CACHE = os.path.join(OUT, "c.npz")
TOK_CACHE = os.path.join(OUT, "tokens.npz")
dev = "cuda" if torch.cuda.is_available() else "cpu"
codec = tok = lm = None
if args.phase in ("codec", "all"):
    print(f"[2/4] loading codec only")
    from miocodec import MioCodecModel
    codec = MioCodecModel.from_pretrained(args.codec).to(dev).eval()
elif args.phase == "lm":
    # LM ONLY. Loading it alongside the codec segfaulted even after splitting
    # the work, because both still had to be resident at once. The LM emits
    # tokens, which are cached; a separate codec-only pass turns them into
    # audio. One model in memory at a time, at the cost of one extra process.
    print(f"[2/4] loading {args.lm} only")
    from transformers import AutoModelForCausalLM, AutoTokenizer
    tok = AutoTokenizer.from_pretrained(args.lm, trust_remote_code=True)
    lm = AutoModelForCausalLM.from_pretrained(args.lm, torch_dtype=torch.bfloat16,
                                              device_map=dev, trust_remote_code=True).eval()
elif args.phase == "decode":
    print(f"[2/4] loading codec only, to decode the cached tokens")
    from miocodec import MioCodecModel
    codec = MioCodecModel.from_pretrained(args.codec).to(dev).eval()


def encode(w24):
    t = torch.as_tensor(librosa.resample(np.asarray(w24, np.float32),
                                         orig_sr=SR_CORPUS, target_sr=SR_CODEC)
                        ).reshape(1, -1).to(dev)
    with torch.no_grad():
        f = codec.encode(t, return_content=True, return_global=True)
    return (f.global_embedding.reshape(-1).float().cpu().numpy(),
            f.content_token_indices.reshape(-1).long().cpu().numpy())


def decode(g, codes):
    ge = torch.as_tensor(np.asarray(g, np.float32), device=dev).reshape(-1)
    ct = torch.as_tensor(np.asarray(codes), dtype=torch.long, device=dev).reshape(-1)
    with torch.no_grad():
        return codec.decode(global_embedding=ge,
                            content_token_indices=ct).squeeze().float().cpu().numpy()


def gen_tokens(text, seed):
    torch.manual_seed(seed)
    p = tok.apply_chat_template([{"role": "user", "content": text}],
                                tokenize=False, add_generation_prompt=True)
    inp = tok(p, return_tensors="pt").to(lm.device)
    with torch.no_grad():
        o = lm.generate(**inp, max_new_tokens=1024, do_sample=True, temperature=0.9,
                        top_p=0.9, pad_token_id=tok.eos_token_id)
    nn = o[0][inp["input_ids"].shape[1]:]
    cc = [t.item() - SPEECH_OFFSET for t in nn
          if SPEECH_OFFSET <= t.item() < SPEECH_OFFSET + CODEBOOK]
    return cc or None


print(f"[3/4] building A / B / C  (phase={args.phase})")
items = []
if args.phase in ("codec", "all"):
    payload = {}
    for i, c in enumerate(clips[:args.items]):
        g, codes = encode(c["wav"])
        A = level(librosa.resample(np.asarray(c["wav"], np.float32),
                                   orig_sr=SR_CORPUS, target_sr=SR_CODEC))
        B = level(decode(g, codes))
        payload[f"A{i}"], payload[f"B{i}"] = A, B
        payload[f"g{i}"] = np.asarray(g, np.float32)
        print(f"      item {i}: A {len(A)/SR_CODEC:.1f}s  B {len(B)/SR_CODEC:.1f}s",
              flush=True)
    payload["n"] = args.items
    payload["texts"] = np.array([c["text"] for c in clips[:args.items]], dtype=object)
    np.savez_compressed(AB_CACHE, **payload)
    print(f"      A/B -> {AB_CACHE}")
    if args.phase == "codec":
        sys.exit(0)

if args.phase == "lm":
    if not os.path.exists(AB_CACHE):
        sys.exit(f"run --phase codec first (missing {AB_CACHE})")
    z = np.load(AB_CACHE, allow_pickle=True)
    out = {}
    for i in range(int(z["n"])):
        cc = gen_tokens(str(z["texts"][i]), args.seed + i)
        if cc is None:
            print(f"      item {i}: no speech tokens")
            continue
        out[f"T{i}"] = np.asarray(cc, np.int64)
        print(f"      item {i}: {len(cc)} tokens", flush=True)
    out["n"] = int(z["n"])
    np.savez_compressed(TOK_CACHE, **out)
    print(f"      tokens -> {TOK_CACHE}")
    sys.exit(0)

if args.phase == "decode":
    for f in (AB_CACHE, TOK_CACHE):
        if not os.path.exists(f):
            sys.exit(f"missing {f}; run --phase codec then --phase lm")
    za, zt = np.load(AB_CACHE, allow_pickle=True), np.load(TOK_CACHE, allow_pickle=True)
    out = {}
    for i in range(int(za["n"])):
        if f"T{i}" not in zt:
            continue
        out[f"C{i}"] = level(decode(za[f"g{i}"], zt[f"T{i}"]))
        print(f"      item {i}: C {len(out[f'C{i}'])/SR_CODEC:.1f}s", flush=True)
    out["n"] = int(za["n"])
    np.savez_compressed(C_CACHE, **out)
    print(f"      C -> {C_CACHE}")
    sys.exit(0)

# phase "pairs": assemble from both caches
if args.phase == "pairs":
    for f in (AB_CACHE, C_CACHE):
        if not os.path.exists(f):
            sys.exit(f"missing {f}; run --phase codec then --phase lm")
    za, zc = np.load(AB_CACHE, allow_pickle=True), np.load(C_CACHE, allow_pickle=True)
    for i in range(int(za["n"])):
        if f"C{i}" not in zc:
            continue
        items.append({"text": str(za["texts"][i]), "A": za[f"A{i}"],
                      "B": za[f"B{i}"], "C": zc[f"C{i}"], "speaker": "?"})
if not items:
    sys.exit("no items built")

# real-vs-real control, from the two clips held back
ctrlA = level(librosa.resample(np.asarray(clips[-1]["wav"], np.float32),
                               orig_sr=SR_CORPUS, target_sr=SR_CODEC))
ctrlB = level(librosa.resample(np.asarray(clips[-2]["wav"], np.float32),
                               orig_sr=SR_CORPUS, target_sr=SR_CODEC))

print("[4/4] writing blind, shuffled pairs")
rng = np.random.default_rng(args.seed)
pairs = []
for k, it in enumerate(items):
    pairs.append(("A_vs_B", "codec cost", it["A"], it["B"], k))
    pairs.append(("B_vs_C", "model cost", it["B"], it["C"], k))
    pairs.append(("A_vs_C", "total", it["A"], it["C"], k))
pairs.append(("control", "real vs real", ctrlA, ctrlB, -1))
pairs.append(("control", "real vs real", ctrlB, ctrlA, -1))

order = rng.permutation(len(pairs))
key = []
for slot, pi in enumerate(order, 1):
    kind, label, x, y, item = pairs[int(pi)]
    flip = rng.random() < 0.5
    first, second = (y, x) if flip else (x, y)
    # which side is the MORE PROCESSED one, i.e. the answer
    more_processed = ("A" if flip else "B") if kind != "control" else "neither"
    sf.write(os.path.join(OUT, f"pair{slot:02d}_1.wav"), first, SR_CODEC)
    sf.write(os.path.join(OUT, f"pair{slot:02d}_2.wav"), second, SR_CODEC)
    key.append({"pair": slot, "kind": kind, "label": label, "item": item,
                "clip1_is": ("second" if flip else "first") + "_of_" + kind,
                "processed_side": 1 if flip else 2,
                "note": "control: both are real recordings" if kind == "control" else ""})
    print(f"      pair{slot:02d}  {label}")

json.dump(key, io.open(os.path.join(OUT, "ANSWER-KEY.json"), "w", encoding="utf-8"),
          ensure_ascii=False, indent=2)

sheet = [
    "# S19 — which sounds more like a real recording?", "",
    "Each pair is two clips of the **same sentence**, level-matched. One question:", "",
    "> **Which sounds more like a real recording of a person — 1 or 2?**", "",
    "You must pick one even when it is close. If they genuinely seem identical,",
    "answer `tie` and say so.", "",
    "Two pairs are **both real recordings** and are there to check the test. If",
    "you can reliably tell those apart on 'realness', you are answering on room",
    "noise or accent rather than on naturalness, and nothing else can be read.",
    "", "| pair | 1, 2 or tie |", "|---|---|"]
sheet += [f"| {i:02d} | |" for i in range(1, len(key) + 1)]
sheet += ["", "Answer key in `out/ANSWER-KEY.json` — **do not open it first.**"]
io.open(os.path.join(OUT, "SCORESHEET.md"), "w", encoding="utf-8").write("\n".join(sheet))

# measurable proxies, so there is a number beside the judgement
print()
print(f"  {'version':<22} {'snr_db':>8} {'hnr_db':>8} {'f0_mean':>9}")
for name, k in (("A real", "A"), ("B codec roundtrip", "B"), ("C full synthesis", "C")):
    vals = [measure(librosa.resample(it[k], orig_sr=SR_CODEC, target_sr=SR_CORPUS),
                    it["text"], SR_CORPUS) for it in items]
    print(f"  {name:<22} {np.nanmean([v.snr_db for v in vals]):>8.1f} "
          f"{np.nanmean([v.hnr_db for v in vals]):>8.2f} "
          f"{np.nanmean([v.f0_mean for v in vals]):>9.1f}")
print(f"\n  {len(key)} pairs -> {OUT}")
