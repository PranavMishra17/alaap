"""
E11 — build the catalog, and find out where it saturates.

GRAND-PLAN section 5 calls a few hundred audited voices "the minimum shippable
thing". This builds it. But minting N voices is not interesting on its own --
what is interesting is the question minting N voices ANSWERS:

    How many distinct identities can this backend actually hold before new
    descriptions stop producing new voices?

That number is the product. A catalog of 500 voices where 300 are audibly the
same voice is a catalog of 200 voices and a support problem. E1 measured
navigability of the SPACE; this measures saturation of the CATALOG, which is
the same geometry seen from the side that ships.

DESIGN. Descriptions are not hand-written -- hand-written descriptions cluster
around whatever the author finds easy to imagine, and that bias would show up
as fake saturation. Instead they are generated by INVERTING the measure-first
pipeline: sample points in bin space, caption them with the same
caption_from_bins that annotates real corpus audio, and mint from those. The
described space is then covered by construction, and every description is one
a real voice could have produced.

Sampling is stratified rather than exhaustive: five axes x five bins is 3,125
cells, and most are uninteresting interiors. We take
  - every EXTREME cell reachable by pushing one axis to its end,
  - a Latin-hypercube-ish random sample of the interior,
so the catalog is dense where voices are ordinary and still probes the corners
where E9 found the quality cliffs.

WHAT IS MEASURED per minted voice
    accepted / rejected  did it clear the uniqueness, drift and consistency
                         floors that service.mint already enforces
    uniqueness           working-space distance to the nearest EXISTING voice
    drift                intended vector vs the vector re-extracted from audio
    consistency          same identity across different sentences

and over the catalog as a whole, as it grows:
    acceptance rate vs catalog size   <- the saturation curve
    nearest-neighbour distance distribution
    Vendi score (normalised)           <- fraction of maximum diversity

The headline is the gap between "voices minted" and "effective number of
voices" = normalised Vendi x n. If 400 mints score 0.22, the catalog holds
about 90 effective voices and RESEARCH/06 would call 0.22 an ALARM.

Runs on 1.7B with the v2 (decorrelated) binner -- the configuration S2 run 4
used, and the only one whose adherence number we still believe. Pass --model
and --binner to override.

    envs/qwen3/Scripts/python.exe experiments/E11-catalog/run_catalog.py --n 300
"""
import argparse
import io
import json
import os
import sys
import time
import warnings

warnings.filterwarnings("ignore")
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", write_through=True)
import numpy as np

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
from alaap.acoustics import Attributes, Binner, BIN_LABELS
from alaap.captions import caption_from_bins
from alaap.geometry import SpeakerSpace
from alaap.encoder import IndependentSV
from alaap.mapper import TextEncoder, RetrievalMapper
from alaap.identity import IdentityStore
from alaap.renderer import Qwen3BaseRenderer
from alaap.watermark import Watermarker
from alaap.service import VoiceService, UNIQUENESS_MIN
from alaap.metrics import vendi_score, nn_distances

HERE = os.path.dirname(os.path.abspath(__file__))

ap = argparse.ArgumentParser()
# Separate output dirs so two novelty arms can be compared side by side
# rather than overwriting each other. out/ holds the novelty=0.0 control.
ap.add_argument("--out", default=os.path.join(HERE, "out"))
# 1.7B + the v2 (decorrelated) binner. This is the configuration S2 run 4
# used to produce the only adherence number we still believe: the 0.6B
# artefacts in S2/out carry a v1 binner, which bins raw f0_std and
# uncorrected hnr_db, and Binner.load refuses to open one. Do not "fix" that
# by re-fitting a v1 -- the entangled axes are what S2 run 3 got wrong.
ap.add_argument("--model", default="Qwen/Qwen3-TTS-12Hz-1.7B-Base")
ap.add_argument("--corpus-cache",
                default="experiments/S2/out/"
                        "corpus_globe_v2_2500_1_Qwen3-TTS-12Hz-17B-Base.npz")
ap.add_argument("--binner", default="experiments/S2/out/"
                                    "binner_globe_v2_Qwen3-TTS-12Hz-17B-Base.json")
ap.add_argument("--n", type=int, default=300)
ap.add_argument("--novelty", type=float, default=0.0)
ap.add_argument("--seed", type=int, default=0)
ap.add_argument("--resume", action="store_true")
args = ap.parse_args()
OUT = args.out
AUD = os.path.join(OUT, "audio")
os.makedirs(AUD, exist_ok=True)

# The five axes that caption_from_bins actually renders into prose, in the
# order it renders them. snr/jitter/shimmer are recording-quality axes; a
# catalog voice should not be described as "very noisy" on purpose.
AXES = ["f0_mean", "spectral_tilt", "hnr_db", "f0_cv", "speaking_rate"]


def sample_cells(n: int, seed: int) -> list[dict[str, str]]:
    """
    Stratified cover of bin space: all one-axis extremes first, then a
    space-filling random sample of the interior. Deterministic in `seed`.
    """
    rng = np.random.default_rng(seed)
    cells, seen = [], set()

    def add(idx):
        key = tuple(idx)
        if key in seen:
            return False
        seen.add(key)
        cells.append({a: BIN_LABELS[a][i] for a, i in zip(AXES, idx)})
        return True

    mid = [2] * len(AXES)
    add(mid)
    # every single-axis extreme, and every single-axis one-step move
    for ai in range(len(AXES)):
        for v in (0, 1, 3, 4):
            idx = list(mid)
            idx[ai] = v
            add(idx)
    # the far corners -- E9 showed these are where identity is most at risk
    for _ in range(min(64, n)):
        add([int(rng.choice([0, 4])) for _ in AXES])
    # interior fill
    guard = 0
    while len(cells) < n and guard < n * 200:
        guard += 1
        add([int(rng.integers(0, 5)) for _ in AXES])
    return cells[:n]


# ------------------------------------------------------------- 1. the mapper
print(f"[1/4] rebuilding the mapper from {args.corpus_cache}")
d = np.load(args.corpus_cache, allow_pickle=True)
Z = d["Z"].astype(np.float64)
attrs = [Attributes.from_dict(a) for a in json.loads(str(d["attrs"]))]
binner = Binner.load(args.binner)
caps = [caption_from_bins(binner.bin_one(a), seed=i) for i, a in enumerate(attrs)]
space = SpeakerSpace.fit(Z, n_components=150)
mapper = RetrievalMapper(space, TextEncoder(), pca_dims=50).fit(caps, Z)
print(f"      {len(caps)} pairs | {space}")

# ------------------------------------------------------------ 2. the service
db = os.path.join(OUT, "catalog.db")
if os.path.exists(db) and not args.resume:
    os.remove(db)
    print("[2/4] starting a fresh catalog (pass --resume to keep the old one)")
store = IdentityStore(db)
svc = VoiceService(renderer=Qwen3BaseRenderer(args.model), space=space,
                   store=store, mapper=mapper, watermarker=Watermarker(),
                   sv=IndependentSV(), audio_dir=os.path.join(OUT, "audio"),
                   is_public=True)
print(f"[2/4] backend {svc.r.backend_id}@{svc.r.backend_version} | "
      f"space_ref {svc.space_ref} | starting from {store.stats()['identities']}")

# --------------------------------------------------------------- 3. mint
cells = sample_cells(args.n, args.seed)
descs = [(f"cat{i:04d}", caption_from_bins(c, seed=i), c)
         for i, c in enumerate(cells)]
print(f"[3/4] minting {len(descs)} voices (novelty {args.novelty})")
print(f"      uniqueness floor {UNIQUENESS_MIN} -- rejections here ARE the result")

# --resume keeps the DB, so it must keep the audit trail too. Starting a fresh
# list overwrote rows.json on the first flush, destroying every row from the
# earlier run -- and re-minted characters the catalog already held, which then
# collided with themselves and burned retries.
rows: list[dict] = []
if args.resume and os.path.exists(os.path.join(OUT, "rows.json")):
    rows = json.load(open(os.path.join(OUT, "rows.json")))
    print(f"      resuming: {len(rows)} rows already logged")
done = {r.get("character_id") for r in rows}
if done:
    skipped = sum(1 for cid, _, _ in descs if cid in done)
    print(f"      skipping {skipped} characters already minted")

t0 = time.time()
vectors: list[np.ndarray] = []
for i, (cid, desc, cell) in enumerate(descs):
    if cid in done:
        continue
    try:
        out = svc.mint(desc, character_id=cid, language="en",
                       novelty=args.novelty, verify=True, tags=["catalog"])
    except Exception as e:
        print(f"      !! {cid}: {type(e).__name__}: {str(e)[:90]}")
        rows.append({"character_id": cid, "description": desc, "cell": cell,
                     "error": f"{type(e).__name__}: {e}"})
        continue
    ident = out.identity
    # Identity.embedding IS the minted vector (tier 1). If it is ever None the
    # mint silently produced a tier-2-only identity, which would quietly drop
    # this voice out of the Vendi measurement -- so notice rather than skip.
    vec = ident.embedding
    if vec is None:
        print(f"      ?? {cid}: tier {ident.tier}, no embedding -- "
              f"excluded from the diversity measure")
    rows.append({
        "character_id": cid, "identity_id": ident.identity_id,
        "description": desc, "cell": cell, "tier": ident.tier,
        "drift": out.drift, "consistency": out.consistency,
        "uniqueness": out.uniqueness, "attempts": out.attempts,
        "warnings": list(out.warnings),
        "clean": not out.warnings,
        "catalog_size_before": i,
    })
    if vec is not None:
        vectors.append(np.asarray(vec, dtype=np.float64))
    if (i + 1) % 10 == 0:
        el = time.time() - t0
        clean = sum(1 for r in rows if r.get("clean"))
        print(f"      {i+1}/{len(descs)} | clean {clean} "
              f"({clean/max(len(rows),1):.0%}) | {el/60:.1f} min | "
              f"eta {el/(i+1)*(len(descs)-i-1)/60:.1f} min", flush=True)
        json.dump(rows, open(os.path.join(OUT, "rows.json"), "w"), indent=2)

json.dump(rows, open(os.path.join(OUT, "rows.json"), "w"), indent=2)

# -------------------------------------------------------------- 4. analyse
print("[4/4] measuring saturation")
ok = [r for r in rows if "error" not in r]
clean = [r for r in ok if r.get("clean")]


def arr(key, src):
    v = [r[key] for r in src if r.get(key) is not None]
    return np.array(v, dtype=np.float64) if v else np.array([])


# saturation curve: clean-acceptance rate in successive blocks of the run
BLOCK = max(20, len(ok) // 10)
curve = []
for s in range(0, len(ok), BLOCK):
    blk = ok[s:s + BLOCK]
    if not blk:
        continue
    curve.append({"from": s, "to": s + len(blk),
                  "clean_rate": sum(1 for r in blk if r.get("clean")) / len(blk),
                  "mean_uniqueness": float(np.mean(arr("uniqueness", blk)))
                  if len(arr("uniqueness", blk)) else None})

summary = {
    "model": args.model, "n_requested": args.n, "n_minted": len(ok),
    "n_clean": len(clean), "n_errors": len(rows) - len(ok),
    "clean_rate": len(clean) / max(len(ok), 1),
    "novelty": args.novelty,
    "drift_mean": float(np.mean(arr("drift", ok))) if len(arr("drift", ok)) else None,
    "drift_min": float(np.min(arr("drift", ok))) if len(arr("drift", ok)) else None,
    "consistency_mean": float(np.mean(arr("consistency", ok)))
    if len(arr("consistency", ok)) else None,
    "uniqueness_mean": float(np.mean(arr("uniqueness", ok)))
    if len(arr("uniqueness", ok)) else None,
    "uniqueness_min": float(np.min(arr("uniqueness", ok)))
    if len(arr("uniqueness", ok)) else None,
    "saturation_curve": curve,
}

if len(vectors) >= 10:
    V = np.vstack(vectors)
    E = space.encode(V)
    # normalise=True returns a FRACTION of maximum diversity, not a count.
    summary["vendi_normalised"] = float(vendi_score(E))
    summary["effective_voices"] = summary["vendi_normalised"] * len(V)
    nn = nn_distances(E)
    summary["nn_median"] = float(np.median(nn))
    summary["nn_p05"] = float(np.percentile(nn, 5))

json.dump(summary, open(os.path.join(OUT, "results.json"), "w"), indent=2)

st = store.stats()
print()
print("=" * 78)
print("E11 — catalog build and saturation")
print("=" * 78)
print(f"  requested          {args.n}")
print(f"  minted             {len(ok)}   ({summary['n_errors']} errors)")
print(f"  clean (no warning) {len(clean)}   ({summary['clean_rate']:.1%})")
if summary.get("drift_mean") is not None:
    print(f"  drift              mean {summary['drift_mean']:.3f}  "
          f"min {summary['drift_min']:.3f}")
if summary.get("consistency_mean") is not None:
    print(f"  consistency        mean {summary['consistency_mean']:.3f}")
if summary.get("uniqueness_mean") is not None:
    print(f"  uniqueness         mean {summary['uniqueness_mean']:.3f}  "
          f"min {summary['uniqueness_min']:.3f}  (floor {UNIQUENESS_MIN})")
if "vendi_normalised" in summary:
    print(f"  VENDI (normalised) {summary['vendi_normalised']:.3f} "
          f"(target >=0.35) = {summary['effective_voices']:.1f} effective "
          f"voices from {len(vectors)} minted")
    print(f"  nn distance        median {summary['nn_median']:.3f}  "
          f"p05 {summary['nn_p05']:.3f}")
print()
print("  saturation — clean-acceptance rate as the catalog fills:")
for c in curve:
    bar = "#" * int(round(c["clean_rate"] * 40))
    print(f"    {c['from']:>4}-{c['to']:<4} {c['clean_rate']:>5.0%} {bar}")
print()
print(f"  store              {st['identities']} identities "
      f"({st['tier1']} tier-1, {st['tier2']} tier-2), {st['renders']} renders")
print(f"  artefacts          {OUT}")
print("=" * 78)
